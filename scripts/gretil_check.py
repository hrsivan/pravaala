"""Cheap check before adding silver-annotated text: how many benchmark words
that are absent or rare in our DCS training corpus are attested in GRETIL?

GRETIL text is raw (sandhied, inflected, compounds unsplit), so a word is
counted through its *paradigm*, generated by analogy with the DCS:
  * from the aligned DCS views, collect rules  lemma = S + x  ->  form = S + y
    (S the longest common prefix), grouped by the lemma's last two letters;
  * for a benchmark word w, apply the frequent rules of its class whose x is a
    suffix of w, and add word-final sandhi variants (-H -> -s/-S/-r/-o..., -m -> -M,
    -t -> -d/-c/-j/-l/-n, -k -> -g/-N);
  * count GRETIL tokens equal to a generated form.
Compound-initial uses (no ending) and vowel-initial words fused by sandhi are
missed, so this undercounts; forms shared with another lemma overcount.

GRETIL contains many DCS texts, so for each word we subtract its DCS count to
estimate *new* occurrences. Lexicons (6_sastra/2_lex) are excluded, as in the
no-lexicon corpus. Kośa verses quoted inside commentaries are not filtered.

usage: python scripts/gretil_check.py --gretil <GRETIL-mirror>/gretil.sub.uni-goettingen.de/gretil/1_sanskr
"""
import argparse
import bisect
import html
import json
import re
import sys
import unicodedata
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from pravaala import benchmarks as bm  # noqa: E402
from pravaala.normalise import canon_nasal  # noqa: E402
from pravaala.translit import iast_to_slp1  # noqa: E402

ap = argparse.ArgumentParser()
ap.add_argument("--gretil", type=Path, required=True)
ap.add_argument("--subset", default="all_nolex+np")
ap.add_argument("--evalsan", type=Path, default=ROOT / "data" / "evalsan_clean")
ap.add_argument("--exclude", nargs="*", default=["6_sastra/2_lex"])
a = ap.parse_args()

IAST_MARKS = set("āīūṛṝḷṃḥṅñṭḍṇśṣ")
TAG = re.compile(r"<[^>]+>")
SPLIT = re.compile(r"[^A-Za-z']+")        # SLP1 letters (+ avagraha) form tokens

files = sorted(p for p in a.gretil.rglob("*.htm")
               if not any(x in p.as_posix() for x in a.exclude))
tok, skipped, used = Counter(), [], 0
for p in files:
    raw = p.read_bytes().decode("utf-8", errors="replace")
    text = unicodedata.normalize("NFC", html.unescape(TAG.sub(" ", raw))).lower()
    marks = sum(ch in IAST_MARKS for ch in text)
    if marks < 0.005 * len(text):          # not IAST (older encodings, prose headers only)
        skipped.append(p.name); continue
    used += 1
    for t in SPLIT.split(iast_to_slp1(text)):
        if len(t) > 1:
            tok[canon_nasal(t)] += 1
types = sorted(tok)
cum = [0]
for t in types:
    cum.append(cum[-1] + tok[t])


# paradigm rules by analogy with the DCS (seg form vs lemma, aligned views)
rules = {}
for fs, fl in zip(open(ROOT / "data" / "corpora" / a.subset / "seg.txt", encoding="utf-8"),
                  open(ROOT / "data" / "corpora" / a.subset / "lem.txt", encoding="utf-8")):
    for f, l in zip(fs.split(), fl.split()):
        if len(l) < 3:
            continue
        k = 0
        while k < min(len(f), len(l)) and f[k] == l[k]:
            k += 1
        if len(l) - k > 3 or len(f) - k > 6 or k < 2:
            continue                            # suppletion / ablaut too strong for analogy
        rules.setdefault(l[-2:], Counter())[(l[k:], f[k:])] += 1
SANDHI = {"H": ["H", "s", "S", "z", "r", ""], "m": ["m", "M"], "t": ["t", "d", "c", "j", "l", "n"],
          "k": ["k", "g", "N"]}


def paradigm(w, top=60, min_share=0.005):
    R = rules.get(w[-2:], Counter())
    tot = sum(R.values()) or 1
    forms = {w}
    for (x, y), c in R.most_common(top):
        if c / tot < min_share or not w.endswith(x):
            continue
        forms.add(w[:len(w) - len(x)] + y)
    out = set()
    for f in forms:
        if f[-1] in SANDHI:
            out |= {f[:-1] + e for e in SANDHI[f[-1]]}
            if f.endswith("aH"):
                out.add(f[:-2] + "o")
            if f.endswith("AH"):
                out.add(f[:-1])
        else:
            out.add(f)
    return {canon_nasal(f) for f in out if len(f) > 1}


def attest(w):
    forms = paradigm(w)
    return sum(tok[f] for f in forms), len(forms)


# benchmark words and their DCS (lemma-view) counts
dcs = Counter()
for line in open(ROOT / "data" / "corpora" / a.subset / "lem.txt", encoding="utf-8"):
    dcs.update(line.split())
test = bm.load_relatedness(a.evalsan, "test")
mcq = bm.load_synonym_mcq(a.evalsan)
words = {canon_nasal(w) for x, y, _ in test for w in (x, y)}
words |= {canon_nasal(w) for q, o in mcq for w in [q, *o]}

rows = {}
for w in words:
    c, nf = attest(w)
    rows[w] = {"dcs": dcs[w], "gretil": c, "n_forms": nf, "new": max(c - dcs[w], 0)}


def band(c):
    return "absent" if c == 0 else "rare (1-4)" if c < 5 else "covered (5+)"


summary = {"files_used": used, "files_skipped_not_iast": len(skipped),
           "gretil_tokens": sum(tok.values()), "gretil_types": len(tok),
           "dcs_lem_tokens": sum(dcs.values()), "bands": {}}
for b in ("absent", "rare (1-4)", "covered (5+)"):
    ws = [w for w in words if band(rows[w]["dcs"]) == b]
    if not ws:
        continue
    reach = lambda t: round(sum(rows[w]["dcs"] + rows[w]["new"] >= t for w in ws) / len(ws), 3)
    summary["bands"][b] = {"n_words": len(ws), "reach5": reach(5), "reach20": reach(20),
                           "median_new": sorted(rows[w]["new"] for w in ws)[len(ws) // 2]}

# projected coverage if every word reaching 5 occurrences got a vector
ok = lambda w: rows[w]["dcs"] + rows[w]["new"] >= 5
summary["proj_rel_cov"] = round(sum(ok(canon_nasal(x)) and ok(canon_nasal(y))
                                    for x, y, _ in test) / len(test), 3)
summary["proj_mcq_cov"] = round(sum(all(ok(canon_nasal(w)) for w in [q, *o])
                                    for q, o in mcq) / len(mcq), 3)
summary["now_rel_cov"] = round(sum(dcs[canon_nasal(x)] >= 5 and dcs[canon_nasal(y)] >= 5
                                   for x, y, _ in test) / len(test), 3)
summary["now_mcq_cov"] = round(sum(all(dcs[canon_nasal(w)] >= 5 for w in [q, *o])
                                   for q, o in mcq) / len(mcq), 3)
out = ROOT / "results" / a.subset / "gretil_check.json"
absent = sorted((w for w in words if rows[w]["dcs"] == 0), key=lambda w: -rows[w]["new"])
json.dump({"summary": summary, "absent_top": {w: rows[w] for w in absent[:40]},
           "absent_unattested_sample": [w for w in absent if rows[w]["gretil"] == 0][:40],
           "paradigm_examples": {w: sorted(paradigm(w)) for w in ["jala", "agni", "nadI", "Bogin"]},
           "skipped": skipped}, open(out, "w"), indent=1, ensure_ascii=False)
print(json.dumps(summary, indent=1))
