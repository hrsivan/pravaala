"""Assemble result tables from exactly the components you select.

usage: python scripts/make_tables.py [--subsets all classical] \
           [--protocols ours evalsan] [--plugins compose] [--models sgns glove] \
           [--views lem lid] [--common_support] [--out report/tables]

Only files matching the selection are read, so excluded subsets, protocols
or plugins leave no trace in the generated LaTeX (report/tables/*.tex) or
Markdown (report/tables/summary.md).

--common_support recomputes relatedness and synonym scores for each
(subset, protocol) group on the intersection of items covered by every
selected run, and adds exact McNemar tests (synonym MCQ) for each pair of
runs on that common set.
"""
import argparse
import itertools
import json
import sys
from pathlib import Path

import numpy as np
from scipy.stats import binomtest, spearmanr

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from pravaala import benchmarks as bm  # noqa: E402
from pravaala.evaluate import auc  # noqa: E402

ap = argparse.ArgumentParser()
ap.add_argument("--results", type=Path, default=ROOT / "results")
ap.add_argument("--subsets", nargs="+", default=["all"])
ap.add_argument("--protocols", nargs="+", default=["ours"])
ap.add_argument("--plugins", nargs="*", default=[])
ap.add_argument("--models", nargs="*", default=None)
ap.add_argument("--views", nargs="*", default=None)
ap.add_argument("--common_support", action="store_true")
ap.add_argument("--evalsan", type=Path, help="needed for --common_support")
ap.add_argument("--out", type=Path, default=ROOT / "report" / "tables")
a = ap.parse_args()
a.out.mkdir(parents=True, exist_ok=True)

tags = list(a.protocols) + [f"plugin_{p}" for p in a.plugins]


def runs(subset):
    for d in sorted((a.results / subset).glob("*/")):
        if not (d / "config.json").exists():
            continue
        cfg = json.load(open(d / "config.json"))
        model, view = cfg["model"], cfg["view"]
        if a.models and model not in a.models or a.views and view not in a.views:
            continue
        yield d, model, view


f = lambda x, p=3: "--" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{x:.{p}f}"
md = ["# Results (generated by make_tables.py)", "",
      f"subsets={a.subsets} protocols={a.protocols} plugins={a.plugins}", ""]
for subset in a.subsets:
    for tag in tags:
        rows = []
        for d, model, view in runs(subset):
            p = d / f"eval_{tag}.json"
            if not p.exists():
                continue
            R = json.load(open(p))
            if tag.startswith("evalsan"):
                rows.append((model, view, R["relatedness_test"]["accuracy"],
                             R["relatedness_test"]["macroF1"], R["synonym_mcq"]["accuracy"],
                             R["synonym_mcq"]["n"], R["cat_sem"]["purity_best_of_6"]))
            else:
                r, s, k = R["relatedness_test"], R["synonym_mcq"], R["ak_varga_kmeans"]
                rows.append((model, view, r["coverage"], r.get("spearman"), r.get("auc_2v0"),
                             s["coverage"], s["acc"], k["nmi"], k["nmi_null"], k["vi"]))
        if not rows:
            continue
        name = f"{subset}_{tag}".replace("+", "_")
        if tag.startswith("evalsan"):
            head = ["model", "view", "rel acc", "rel F1", "syn acc", "syn n", "cat purity*"]
        else:
            head = ["model", "view", "rel cov", "rho", "AUC20", "syn cov", "syn acc",
                    "AK NMI", "null", "AK VI"]
        body = [[r[0], r[1]] + [f(x) if not isinstance(x, int) else str(x) for x in r[2:]]
                for r in rows]
        tex = ["\\begin{tabular}{" + "ll" + "r" * (len(head) - 2) + "}", "\\toprule",
               " & ".join(head) + " \\\\", "\\midrule",
               *(" & ".join(b) + " \\\\" for b in body), "\\bottomrule", "\\end{tabular}"]
        (a.out / f"{name}.tex").write_text("\n".join(tex) + "\n")
        md += [f"## {subset} / {tag}", "", "| " + " | ".join(head) + " |",
               "|" + "---|" * len(head), *("| " + " | ".join(b) + " |" for b in body), ""]

        if a.common_support and not tag.startswith("evalsan"):
            if not a.evalsan:
                sys.exit("--common_support needs --evalsan")
            y = np.array([t for *_, t in bm.load_relatedness(a.evalsan, "test")])
            I = {}
            for d, model, view in runs(subset):
                p = d / f"items_{tag}.json"
                if p.exists():
                    I[f"{model}/{view}"] = json.load(open(p))
            if len(I) < 2:
                continue
            rel = set.intersection(*(set(v["relatedness_test"]) for v in I.values()))
            syn = set.intersection(*(set(v["synonym_mcq"]) for v in I.values()))
            md += [f"### common support: relatedness n={len(rel)}, synonym n={len(syn)}", "",
                   "| run | rho | AUC20 | syn acc |", "|---|---|---|---|"]
            for k, v in I.items():
                ids = sorted(rel, key=int)
                s = np.array([v["relatedness_test"][i] for i in ids]); yy = y[[int(i) for i in ids]]
                rho = spearmanr(s, yy).statistic if len(ids) > 2 else None
                a20 = auc(s[yy == 2], s[yy == 0]) if len(ids) > 2 else None
                acc = np.mean([v["synonym_mcq"][i] for i in syn]) if syn else None
                md.append(f"| {k} | {f(rho)} | {f(a20)} | {f(acc)} |")
            md += ["", "McNemar exact (synonym MCQ, common support):", ""]
            for (k1, v1), (k2, v2) in itertools.combinations(I.items(), 2):
                b = sum(v1["synonym_mcq"][i] > v2["synonym_mcq"][i] for i in syn)
                c = sum(v1["synonym_mcq"][i] < v2["synonym_mcq"][i] for i in syn)
                p = binomtest(b, b + c).pvalue if b + c else 1.0
                md.append(f"* {k1} vs {k2}: b={b}, c={c}, p={p:.3g}")
            md.append("")

(a.out / "summary.md").write_text("\n".join(md) + "\n")
print("\n".join(md))
